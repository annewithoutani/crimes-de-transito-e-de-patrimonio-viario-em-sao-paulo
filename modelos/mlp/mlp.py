"""## Relatório: como ler os resultados

### As duas perguntas que o relatório responde

1. **O total de crimes está bom?** Métricas em nº de crimes ou em % do volume:

| métrica | o que mede | unidade | leitura |
|---|---|---|---|
| `MAE` | erro absoluto médio por registro | crimes | menor = melhor |
| `Mediana do \|erro\|` | erro "típico" (robusto a outliers) | crimes | menor = melhor |
| `RMSE` | erro quadrático médio | crimes | penaliza erros grandes; maior que o MAE sinaliza cauda pesada |
| `WAPE` | Σ\|erro\| ÷ Σreal | % | **proxy de precisão**: 26% = errei 26% do volume total |
| `Acerto ±tolerância` | % de registros com \|erro\| ≤ max(2, 10%·real) | % | maior = melhor (tolerância escolhida por convenção) |
| `R²` | variação explicada | 0–1 | 1 = perfeito; 0 = igual a chutar a média |
| `Sesgo médio` | erro com sinal (previsto − real) | crimes | \>0 = superestima, <0 = subestima |

2. **O mix de tipos de crime está bom?** Mesmas ideias, mas em **pontos
percentuais (p.p.)** — um erro de 20 p.p. quer dizer que a proporção prevista
ficou a 20 pontos percentuais da real (ex.: previu 35% e o real era 55%).

### Skill-score (o número-resumo)

`skill = 1 − erro_MLP ÷ erro_persistência`, em %. É o quanto o modelo **melhora
sobre simplesmente repetir o que aconteceu em 2022–23**. `> 0` = aprendeu algo;
`≈ 0` = não passa do baseline; `< 0` = pior do que não fazer nada.

### Faixas heurísticas de julgamento (WAPE do total)

| WAPE | leitura |
|---|---|
| < 10% | excelente |
| 10–20% | bom |
| 20–30% | razoável — **é onde estamos (~26%)**, considerando mediana de 4 B.O.s/registro |
| 30–50% | fraco |
| > 50% | pouco útil |

Para `R²`: >0,9 forte · 0,7–0,9 bom · 0,5–0,7 moderado · <0,5 fraco.
Para skill-score: >10% ganho relevante · 0–10% ganho modesto · ≤0 sem ganho.
(São heurísticas de domínio, não verdades universais.)

**Nota:** as métricas de `Acerto ±tolerância` podem *discordar* do MAE/RMSE.
A persistência acerta mais registros isolados mesmo com erro médio maior; já a MLP
reduz o erro total ao preço de errar um pouco mais nos casos pequenos. Olhe as duas.

"""

