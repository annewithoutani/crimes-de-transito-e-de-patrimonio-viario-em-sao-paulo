JANELA_ALVO = (2024, 2025)  # janela dos alvos (total + proporções)

EXCLUIR_HORA_INCERTA = False   # True: descarta os 14.774 B.O.s com DESC_PERIODO == 'EM HORA INCERTA'
INCLUIR_MIX_HISTORICO = True   # True: usa as proporções da janela A como features de histórico

N_ITER_BUSCA = 30   # avaliações do RandomizedSearchCV
N_FOLDS = 5
N_JOBS = -1         # processos paralelos; cada um com 1 thread de BLAS
SEED = 42

CARREGAR_MODELO = True    # True: exige mlp_melhor.joblib e pula a busca; False: treina do zero
REUSAR_REGISTROS = True   # True: se registros.csv existir, pula a leitura do CSV de 173 MB e a agregação
RODAR_IMPORTANCIA = True  # False: pula permutation_importance e o gráfico de importância

ARQ_REGISTROS = "registros.csv"
ARQ_MODELO = "mlp_melhor.joblib"
ARQ_BUSCA = "busca_hiperparametros.csv"

