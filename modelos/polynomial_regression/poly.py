def _para_clr(props_pct: np.ndarray) -> np.ndarray:
    """proporções em % -> log-razão centrada (trata zeros com EPS_CLR)."""
    q = np.clip(props_pct / 100.0, 0.0, None) + EPS_CLR
    lg = np.log(q)
    return lg - lg.mean(axis=1, keepdims=True)


def _de_clr(z: np.ndarray) -> np.ndarray:
    """log-razão centrada -> proporções em % (positivas, somando 100)."""
    z = z - z.max(axis=1, keepdims=True)
    q = np.exp(z)
    return 100.0 * q / q.sum(axis=1, keepdims=True)


def normalizar_props(p: np.ndarray) -> np.ndarray:
    """corta negativos e re-normaliza cada linha para somar 100%."""
    p = np.clip(p, 0.0, None)
    soma = p.sum(axis=1, keepdims=True)
    return np.divide(p * 100.0, soma, out=np.zeros_like(p), where=soma > 0)


def y_para_treino(y: np.ndarray) -> np.ndarray:
    """total -> log1p | proporções -> CLR ou fração 0..1, conforme TRANSFORMAR_MIX."""
    yt = np.array(y, dtype=float, copy=True)
    yt[:, 0] = np.log1p(yt[:, 0])
    if TRANSFORMAR_MIX == "clr":
        yt[:, 1:] = _para_clr(yt[:, 1:])
    else:
        yt[:, 1:] = yt[:, 1:] / 100.0
    return yt


def y_original(yt: np.ndarray) -> np.ndarray:
    """desfaz a transformação, corta o total em [0, TETO_TOTAL] e renormaliza o mix."""
    y = np.array(yt, dtype=float, copy=True)
    y[:, 0] = np.clip(np.expm1(y[:, 0]), 0.0, TETO_TOTAL)
    if TRANSFORMAR_MIX == "clr":
        y[:, 1:] = _de_clr(y[:, 1:])
    y[:, 1:] = normalizar_props(y[:, 1:])
    return y


